/** Kartu ringkasan satu angka (KPI): ikon, label, nilai (+ akhiran %), nilai teks lebih kecil. */
export function KartuKpi({ kpi }: { kpi: Kpi }) {
  const nilai = typeof kpi.value === "number" ? kpi.value.toLocaleString("id-ID") : kpi.value;
  return (
    <div className="rounded-xl border border-slate-200 bg-white p-6">
      <div className="mb-3 flex h-9 w-9 items-center justify-center rounded-lg bg-emerald-50 text-sidebar">
        <Ikon nama={kpi.icon} />
      </div>
      <div className="text-xs text-slate-500">{kpi.label}</div>
      <div className={`${kpi.teks ? "text-base" : "text-2xl"} mt-1 font-bold text-slate-900`}>
        {nilai}
        {kpi.suffix ?? ""}
      </div>
    </div>
  );
}
